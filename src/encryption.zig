test "SEC-0039: u32 overflow bounds check arithmetic" {
    // Verify that the bounds check at `blob.len - BLOB_LEN_SIZE > maxInt(u32)`
    // correctly guards the @intCast. We can't allocate >4 GiB in a test, so
    // instead we verify the arithmetic properties that the check relies on.

    // Any blob whose content length exceeds maxInt(u32) must be rejected.
    const max_u32: usize = std.math.maxInt(u32);

    // blob.len = maxInt(u32) + BLOB_LEN_SIZE is the last value that fits.
    const ok_remaining = max_u32;
    try std.testing.expect(ok_remaining <= max_u32);

    // blob.len = maxInt(u32) + BLOB_LEN_SIZE + 1 overflows u32.
    const overflow_remaining = max_u32 + 1;
    try std.testing.expect(overflow_remaining > max_u32);

    // Also verify the check exists in both functions by calling with a
    // minimal blob that has a mismatched blob_len (exercises the path).
    const allocator = std.testing.allocator;
    var key: [32]u8 = undefined;
    std.crypto.random.bytes(&key);

    // Craft a buffer exactly at ENCRYPTION_OVERHEAD but with blob_len
    // set to a value that doesn't match (e.g., 0xFFFFFFFF).
    var bad_blob: [ENCRYPTION_OVERHEAD]u8 = undefined;
    @memcpy(bad_blob[OFF_MAGIC..][0..MAGIC_SIZE], &MAGIC);
    std.mem.writeInt(u32, bad_blob[OFF_BLOB_LEN..][0..4], 0xFFFFFFFF, .little);

    // decryptRecord: blob_len mismatch → InvalidEncryptedRecord.
    try std.testing.expectError(error.InvalidEncryptedRecord, decryptRecord(allocator, &key, &bad_blob));
    // decryptRecordInPlace: same check.
    try std.testing.expectError(error.InvalidEncryptedRecord, decryptRecordInPlace(&key, &bad_blob));
}
