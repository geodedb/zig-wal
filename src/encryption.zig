//! Optional AES-256-GCM per-record encryption layer.
//!
//! All functions are pure (no file I/O). Callers are responsible for key
//! management and for freeing allocator-owned slices returned by
//! `encryptRecord` and `decryptRecord`.
//!
//! Encrypted record format on disk:
//! ```
//! [blob_len: u32 LE][magic: "ZIGWALE\x00" (8)][nonce: (12)][tag: (16)][ciphertext]
//! ```
//! - `blob_len` is the byte count of everything AFTER the blob_len field
//!   (magic + nonce + tag + ciphertext).
//! - Total overhead per record: 4 + 8 + 12 + 16 = 40 bytes (plus ciphertext
//!   which is the same length as the plaintext).
//!
//! ## Nonce management (SEC-0007)
//!
//! Each record's 96-bit nonce is generated by `std.crypto.random` (OS CSPRNG).
//! AES-256-GCM's security guarantee degrades after approximately 2^32 encryptions
//! under the same key due to the birthday-bound probability of a nonce collision.
//! A nonce collision with AES-GCM leaks the XOR of two plaintexts and can enable
//! forgery of authentication tags.
//!
//! **Callers must rotate the encryption key before a single key is used for 2^32
//! records.** For most WAL workloads this is not a practical concern (4 billion
//! records at 1 KB each ≈ 4 TB of WAL data before compaction), but high-throughput
//! systems should implement key rotation as a defence-in-depth measure.

const std = @import("std");
const Aes256Gcm = std.crypto.aead.aes_gcm.Aes256Gcm;
const record = @import("record.zig");

// ============================================================================
// Constants
// ============================================================================

/// Magic bytes written at offset 4 of every encrypted record.
pub const MAGIC: [8]u8 = "ZIGWALE\x00".*;

/// Size of the magic field in bytes.
pub const MAGIC_SIZE: usize = 8;

/// Size of the AES-256-GCM nonce in bytes (96-bit random nonce).
pub const NONCE_SIZE: usize = Aes256Gcm.nonce_length; // 12

/// Size of the AES-256-GCM authentication tag in bytes.
pub const TAG_SIZE: usize = Aes256Gcm.tag_length; // 16

/// Size of the blob_len prefix field in bytes.
pub const BLOB_LEN_SIZE: usize = 4;

/// Total per-record overhead (blob_len + magic + nonce + tag).
/// The ciphertext is the same length as the plaintext, so total encrypted
/// record size = `ENCRYPTION_OVERHEAD + plaintext.len`.
pub const ENCRYPTION_OVERHEAD: usize = BLOB_LEN_SIZE + MAGIC_SIZE + NONCE_SIZE + TAG_SIZE; // 40

/// Minimum bytes needed to detect an encrypted record: blob_len (4) + magic (8).
/// Used as the peek buffer size across recovery, compaction, and iteration (QA-0014).
pub const DETECT_PEEK_SIZE: usize = BLOB_LEN_SIZE + MAGIC_SIZE; // 12

// Byte offsets within a serialised encrypted record, derived from field sizes (QA-0066).
const OFF_BLOB_LEN: usize = 0;
const OFF_MAGIC: usize = OFF_BLOB_LEN + BLOB_LEN_SIZE;
const OFF_NONCE: usize = OFF_MAGIC + MAGIC_SIZE;
const OFF_TAG: usize = OFF_NONCE + NONCE_SIZE;
const OFF_CIPHERTEXT: usize = OFF_TAG + TAG_SIZE;

comptime {
    // Lock the invariant: ciphertext starts exactly at the encryption overhead boundary.
    if (OFF_CIPHERTEXT != ENCRYPTION_OVERHEAD) @compileError("OFF_CIPHERTEXT must equal ENCRYPTION_OVERHEAD");
}

// ============================================================================
// Errors
// ============================================================================

pub const EncryptionError = error{
    /// The blob_len field, magic bytes, or overall buffer size is wrong.
    InvalidEncryptedRecord,
    /// AES-256-GCM authentication tag verification failed (wrong key or
    /// tampered data).
    DecryptionFailed,
    /// The environment variable value is not a valid 64-hex-digit key.
    InvalidKey,
    /// The plaintext is too large for the encrypted blob_len u32 field.
    /// blob_len = MAGIC_SIZE + NONCE_SIZE + TAG_SIZE + plaintext.len must
    /// fit in a u32. Maximum plaintext: maxInt(u32) - 36 bytes (SEC-0033).
    PayloadTooLarge,
};

// ============================================================================
// Security helpers
// ============================================================================

/// Zeroize a byte slice using volatile writes to prevent the compiler from
/// optimising away the clear. Use this for key material (SEC-0002).
/// Delegates to std.crypto.secureZero (QA-0048).
pub fn secureZero(buf: []u8) void {
    // Cast non-volatile slice to volatile for the stdlib call.
    const vol: []volatile u8 = @volatileCast(buf);
    std.crypto.secureZero(u8, vol);
}

// ============================================================================
// Shared encrypted record reader (QA-0002)
// ============================================================================

/// Result of `readEncryptedBlob`.  The caller owns `blob` and must call
/// `secureZero` + `allocator.free` when done.
pub const EncryptedBlob = struct {
    /// Full encrypted record bytes (blob_len prefix through ciphertext).
    blob: []u8,
    /// Total on-disk size of the record (`BLOB_LEN_SIZE + blob_len`).
    total_on_disk: usize,
};

/// Read the remainder of an encrypted record from `file`, given the
/// `DETECT_PEEK_SIZE` bytes that were already consumed.
///
/// Returns `null` if the record is corrupt (invalid blob_len, too large,
/// or torn write).  On success the caller owns `result.blob` and must
/// call `secureZero(result.blob)` + `allocator.free(result.blob)`.
///
/// This function consolidates the duplicated peek→read→assemble logic
/// that was previously copy-pasted across `recovery.zig`, `compaction.zig`,
/// and `wal.zig` Iterator (QA-0002).
pub fn readEncryptedBlob(
    allocator: std.mem.Allocator,
    source: anytype,
    peek_buf: *const [DETECT_PEEK_SIZE]u8,
) !?EncryptedBlob {
    const blob_len = std.mem.readInt(u32, peek_buf[0..4], .little);
    const total_on_disk: usize = BLOB_LEN_SIZE + @as(usize, blob_len);

    if (total_on_disk < DETECT_PEEK_SIZE) return null; // corrupt blob_len
    // Reject unreasonably large records to prevent OOM (SEC-0004).
    if (total_on_disk > record.MAX_RECORD_SIZE) return null;

    const remaining = total_on_disk - DETECT_PEEK_SIZE;

    const blob_buf = try allocator.alloc(u8, total_on_disk);
    errdefer {
        secureZero(blob_buf);
        allocator.free(blob_buf);
    }

    @memcpy(blob_buf[0..DETECT_PEEK_SIZE], peek_buf);

    if (remaining > 0) {
        const n = try source.readAll(blob_buf[DETECT_PEEK_SIZE..]);
        if (n < remaining) {
            // Torn write — errdefer does not fire on null return, free manually.
            secureZero(blob_buf);
            allocator.free(blob_buf);
            return null;
        }
    }

    return EncryptedBlob{
        .blob = blob_buf,
        .total_on_disk = total_on_disk,
    };
}

/// Like `readEncryptedBlob`, but reuses a caller-owned buffer to avoid
/// per-record allocation churn in scan loops (PERF-0016).
///
/// `reuse_buf` is an optional pre-allocated buffer. If it is large enough,
/// the record is read into it directly. Otherwise it is freed (with
/// `secureZero`) and replaced with a newly allocated buffer of the required
/// size. On first call, pass `null` — the function allocates as needed.
///
/// On success, `reuse_buf.*` points to the (possibly grown) buffer and the
/// returned `EncryptedBlob.blob` is a slice into it. The caller must NOT
/// free `reuse_buf.*` between iterations — only after the scan loop ends.
///
/// Returns `null` on corrupt/torn records (same semantics as
/// `readEncryptedBlob`).
pub fn readEncryptedBlobReuse(
    allocator: std.mem.Allocator,
    source: anytype,
    peek_buf: *const [DETECT_PEEK_SIZE]u8,
    reuse_buf: *?[]u8,
) !?EncryptedBlob {
    const blob_len = std.mem.readInt(u32, peek_buf[0..4], .little);
    const total_on_disk: usize = BLOB_LEN_SIZE + @as(usize, blob_len);

    if (total_on_disk < DETECT_PEEK_SIZE) return null; // corrupt blob_len
    // Reject unreasonably large records to prevent OOM (SEC-0004).
    if (total_on_disk > record.MAX_RECORD_SIZE) return null;

    const remaining = total_on_disk - DETECT_PEEK_SIZE;

    // Grow the reusable buffer if needed.
    if (reuse_buf.*) |buf| {
        if (buf.len < total_on_disk) {
            secureZero(buf); // SEC-0029: clear old content before free
            allocator.free(buf);
            reuse_buf.* = try allocator.alloc(u8, total_on_disk);
        } else {
            // Existing buffer is large enough — secureZero only the used
            // portion from the previous iteration (PERF-0011 principle).
            secureZero(buf[0..@min(buf.len, total_on_disk)]);
        }
    } else {
        reuse_buf.* = try allocator.alloc(u8, total_on_disk);
    }

    const blob_buf = reuse_buf.*.?;

    @memcpy(blob_buf[0..DETECT_PEEK_SIZE], peek_buf);

    if (remaining > 0) {
        const n = try source.readAll(blob_buf[DETECT_PEEK_SIZE..total_on_disk]);
        if (n < remaining) {
            return null; // torn write — buffer retained for reuse
        }
    }

    return EncryptedBlob{
        .blob = blob_buf[0..total_on_disk],
        .total_on_disk = total_on_disk,
    };
}

