test "SEC-0033: blob_len overflow boundary arithmetic" {
    // SEC-0033: blob_len = MAGIC_SIZE + NONCE_SIZE + TAG_SIZE + plaintext.len
    // must fit in u32. Maximum plaintext.len = maxInt(u32) - 36.
    // We can't allocate 4 GiB in a test, so verify the boundary arithmetic
    // that the bounds check uses is correct.
    const overhead = MAGIC_SIZE + NONCE_SIZE + TAG_SIZE; // 36
    try std.testing.expectEqual(@as(usize, 36), overhead);

    // Max plaintext length that fits in u32 blob_len.
    const max_ok: usize = std.math.maxInt(u32) - overhead;
    try std.testing.expectEqual(@as(usize, std.math.maxInt(u32)), overhead + max_ok);

    // One byte more overflows u32.
    try std.testing.expect(overhead + max_ok + 1 > std.math.maxInt(u32));

    // Verify PayloadTooLarge is in EncryptionError set.
    const err: EncryptionError = error.PayloadTooLarge;
    try std.testing.expectEqual(error.PayloadTooLarge, err);
}

